const wordWidth = (word: string, f: Font) => word.length * (f.w + 1) - 1;

/** Greedy word wrap in glyph cells; null if a single word can't fit. */
function wrap(words: string[], f: Font, s: number, maxW: number): string[] | null {
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    if (wordWidth(w, f) * s > maxW) return null;
    const next = line ? `${line} ${w}` : w;
    if (wordWidth(next, f) * s <= maxW) line = next;
    else {
      lines.push(line);
      line = w;
    }
  }
  if (line) lines.push(line);
  return lines;
}

/** A cols×rows mask (255 = lit) with `text` set as large as it fits, or
 *  null if it can't be set legibly (unsupported characters, tiny grid). */
export function pixelLabel(text: string, cols: number, rows: number, split = false): Uint8Array | null {
  const clean = text.toUpperCase().replace(/[^A-Z0-9 .\-/]/g, "").trim();
  if (!clean) return null;
  const maxW = Math.floor(cols * 0.9);
  const maxH = Math.floor(rows * 0.8);
  let words = clean.split(/\s+/);
  // Last resort on narrow grids: break long words into balanced pieces.
  if (split) {
    const fit = Math.floor((maxW + 1) / (F3.w + 1));
    words = words.flatMap((w) => {
      if (w.length <= fit) return [w];
      const parts = Math.ceil(w.length / fit);
      const size = Math.ceil(w.length / parts);
      return Array.from({ length: parts }, (_, i) => w.slice(i * size, (i + 1) * size));
    });
  }
  for (const f of split ? [F3] : [F5, F3]) {
    for (let s = 8; s >= 1; s--) {
      const lines = wrap(words, f, s, maxW);
      if (!lines) continue;
      const lineH = f.h * s;
      const gap = 2 * s;
      const h = lines.length * lineH + (lines.length - 1) * gap;
      if (h > maxH) continue;
      const mask = new Uint8Array(cols * rows);
      const top = Math.floor((rows - h) / 2);
      lines.forEach((line, li) => {
        const left = Math.floor((cols - wordWidth(line, f) * s) / 2);
        const y0 = top + li * (lineH + gap);
        [...line].forEach((ch, ci) => {
          const g = f.glyphs[ch];
          if (!g) return;
          const x0 = left + ci * (f.w + 1) * s;
          for (let gy = 0; gy < f.h; gy++)
            for (let gx = 0; gx < f.w; gx++) {
              if (g[gy][gx] !== "#") continue;
              for (let dy = 0; dy < s; dy++)
                for (let dx = 0; dx < s; dx++) mask[(y0 + gy * s + dy) * cols + x0 + gx * s + dx] = 255;
            }
        });
      });
      return mask;
    }
  }
  return null;
}
